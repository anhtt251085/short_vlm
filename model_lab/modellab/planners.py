"""Turn configs and validated datasets into ready-to-run training jobs for a GPU machine.

Nothing here trains a model. Each planner checks the licence gate, checks the data,
writes the trainer's config files and a launch script, and records the plan with a cost estimate.

Trainer command lines follow each project's documentation as of 2025-2026. Pin the trainer
version in the config and check the flags against that version before running.
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

from .audio_data import load_manifest
from .consent import Ledger, needed_scopes
from .registry import Registry


def load_yaml(path: str | Path) -> dict:
    return yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {}


def estimate_cost(gpu: dict) -> dict:
    hours = gpu.get("est_hours")
    price = gpu.get("hourly_usd")
    cost = round(hours * price, 2) if hours is not None and price is not None else None
    return {"gpu": gpu.get("name"), "est_hours": hours, "hourly_usd": price,
            "est_cost_usd": cost, "note": None if cost is not None else "set gpu.hourly_usd and gpu.est_hours"}


def _toml_list(values) -> str:
    return "[" + ", ".join(json.dumps(v) for v in values) + "]"


# ---------------------------------------------------------------- video LoRA (musubi-tuner)

def plan_video(config_path: str | Path, registry: Registry, dataset_dir: str | Path, out_root: str | Path) -> dict:
    cfg = load_yaml(config_path)
    mode = cfg.get("mode", "commercial")
    model = registry.require(cfg["base_model"], mode)
    if model.task != "text_to_video":
        raise ValueError(f"{model.id} is not a text-to-video model")
    if model.trainer != "musubi-tuner" or not model.trainer_task:
        raise ValueError(f"{model.id} has no musubi-tuner task configured in the registry")

    dataset_dir = Path(dataset_dir).resolve()
    videos = sorted((dataset_dir / "videos").glob("*.mp4"))
    if not videos:
        raise ValueError(f"no clips in {dataset_dir / 'videos'}; run video-data first")
    missing_captions = [v.name for v in videos if not v.with_suffix(".txt").exists()]
    if missing_captions:
        raise ValueError(f"clips without captions: {missing_captions[:5]}")

    run_dir = Path(out_root).resolve() / cfg["run_name"]
    run_dir.mkdir(parents=True, exist_ok=True)
    t = cfg["training"]
    paths = cfg["paths"]

    dataset_toml = run_dir / "dataset.toml"
    dataset_toml.write_text(
        "# Generated by modellab for musubi-tuner. Check keys against the pinned trainer version.\n"
        "[general]\n"
        f"resolution = {_toml_list(cfg['resolution'])}\n"
        'caption_extension = ".txt"\n'
        "batch_size = 1\n"
        "enable_bucket = true\n"
        "bucket_no_upscale = false\n\n"
        "[[datasets]]\n"
        f"video_directory = {json.dumps(str(dataset_dir / 'videos'))}\n"
        f"cache_directory = {json.dumps(str(run_dir / 'cache'))}\n"
        f"target_frames = {_toml_list(cfg['target_frames'])}\n"
        f"frame_extraction = {json.dumps(cfg.get('frame_extraction', 'head'))}\n",
        encoding="utf-8",
    )

    high_noise = ""
    if model.needs_high_noise_dit:
        if not paths.get("dit_high_noise"):
            raise ValueError(f"{model.id} needs paths.dit_high_noise")
        high_noise = f' --dit_high_noise "{paths["dit_high_noise"]}"'
    fp8 = " --fp8_base" if t.get("fp8_base", True) else ""
    out_dir = run_dir / "output"
    script = f"""#!/usr/bin/env bash
# Generated by modellab: video LoRA for {model.id} ({model.license}).
# Targets musubi-tuner (kohya-ss); pinned version: {cfg.get('trainer_version', 'NOT PINNED')}.
# Check every flag against that version's README before running. Needs a GPU with >= {model.min_vram_gb} GB.
set -euo pipefail
MUSUBI_DIR="${{MUSUBI_DIR:?set MUSUBI_DIR to your musubi-tuner checkout}}"
cd "$MUSUBI_DIR"

python src/musubi_tuner/wan_cache_latents.py --dataset_config "{dataset_toml}" --vae "{paths['vae']}"
python src/musubi_tuner/wan_cache_text_encoder_outputs.py --dataset_config "{dataset_toml}" --t5 "{paths['t5']}" --batch_size 16

accelerate launch --num_cpu_threads_per_process 1 --mixed_precision bf16 src/musubi_tuner/wan_train_network.py \\
  --task {model.trainer_task} --dit "{paths['dit']}"{high_noise} \\
  --dataset_config "{dataset_toml}" --sdpa --mixed_precision bf16{fp8} \\
  --optimizer_type adamw8bit --learning_rate {t['learning_rate']} --gradient_checkpointing \\
  --max_data_loader_n_workers 2 --persistent_data_loader_workers \\
  --network_module networks.lora_wan --network_dim {t['network_dim']} \\
  --timestep_sampling shift --discrete_flow_shift 3.0 \\
  --max_train_epochs {t['max_train_epochs']} --save_every_n_epochs {t['save_every_n_epochs']} --seed {t.get('seed', 42)} \\
  --output_dir "{out_dir}" --output_name "{cfg['run_name']}"
"""
    run_sh = run_dir / "run.sh"
    run_sh.write_text(script, encoding="utf-8")
    run_sh.chmod(0o755)

    plan = {
        "kind": "video_lora", "run_name": cfg["run_name"], "mode": mode,
        "base_model": model.id, "license": model.license, "trainer": "musubi-tuner",
        "trainer_version": cfg.get("trainer_version"), "clips": len(videos),
        "trigger": cfg.get("trigger"), "files": [str(dataset_toml), str(run_sh)],
        "cost": estimate_cost(cfg.get("gpu", {})),
    }
    (run_dir / "plan.json").write_text(json.dumps(plan, indent=2, ensure_ascii=False), encoding="utf-8")
    return plan


# ---------------------------------------------------------------- speech model (TTS)

def plan_tts(config_path: str | Path, registry: Registry, dataset_dir: str | Path,
             voices_path: str | Path, out_root: str | Path) -> dict:
    cfg = load_yaml(config_path)
    voices = load_yaml(voices_path)
    mode = cfg.get("mode", "commercial")
    model = registry.require(cfg["base_model"], mode)
    if model.task != "text_to_speech":
        raise ValueError(f"{model.id} is not a text-to-speech model")

    dataset_dir = Path(dataset_dir).resolve()
    manifest = load_manifest(dataset_dir / "manifest.jsonl")
    if not manifest:
        raise ValueError("manifest is empty; run audio-data first")
    langs = {voices["accents"][r["accent"]]["language"] for r in manifest}
    unsupported = sorted(l for l in langs if model.languages and l not in model.languages)
    if unsupported:
        raise ValueError(f"{model.id} does not cover languages {unsupported}; train separate models per language")

    min_minutes = voices["methods"]["tts_speaker"]["min_minutes"]
    minutes: dict[str, float] = {}
    for r in manifest:
        minutes[r["speaker"]] = minutes.get(r["speaker"], 0.0) + r["duration"] / 60
    warnings = [f"speaker {s} has {m:.1f} min (< {min_minutes} min target)"
                for s, m in sorted(minutes.items()) if m < min_minutes]

    run_dir = Path(out_root).resolve() / cfg["run_name"]
    run_dir.mkdir(parents=True, exist_ok=True)
    backend = model.trainer
    if backend == "melotts":
        body = f"""MELO_DIR="${{MELO_DIR:?set MELO_DIR to your MeloTTS checkout (melo/ folder)}}"
cd "$MELO_DIR"
# Writes config.json next to the metadata file; edit batch size there if you run out of memory.
python preprocess_text.py --metadata "{dataset_dir / 'metadata.list'}"
bash train.sh "{dataset_dir / 'config.json'}" {cfg.get('gpus', 1)}
"""
    else:
        body = f"""# {backend}: follow the project's own fine-tuning guide.
# Dataset is exported in LJSpeech style at {dataset_dir / 'metadata.csv'} with audio in {dataset_dir / 'wavs'}.
echo "Fill in the {backend} fine-tuning command from its README before running." >&2
exit 1
"""
    script = f"""#!/usr/bin/env bash
# Generated by modellab: speech model fine-tune for {model.id} ({model.license}).
# Trainer: {backend}; pinned version: {cfg.get('trainer_version', 'NOT PINNED')}.
set -euo pipefail
{body}"""
    run_sh = run_dir / "run.sh"
    run_sh.write_text(script, encoding="utf-8")
    run_sh.chmod(0o755)

    plan = {
        "kind": "tts_finetune", "run_name": cfg["run_name"], "mode": mode,
        "base_model": model.id, "license": model.license, "trainer": backend,
        "trainer_version": cfg.get("trainer_version"), "items": len(manifest),
        "minutes_by_speaker": {k: round(v, 2) for k, v in sorted(minutes.items())},
        "warnings": warnings, "files": [str(run_sh)], "cost": estimate_cost(cfg.get("gpu", {})),
    }
    (run_dir / "plan.json").write_text(json.dumps(plan, indent=2, ensure_ascii=False), encoding="utf-8")
    return plan


# ---------------------------------------------------------------- voice matrix (accent x voice type)

def voice_matrix(voices_path: str | Path, ledger: Ledger, registry: Registry,
                 vc_model: str | None = None, manifest_path: str | Path | None = None,
                 mode: str = "commercial") -> list[dict]:
    """For each planned accent and voice type: how it is made, who can supply it, and what is missing."""
    voices = load_yaml(voices_path)
    methods = voices["methods"]
    minutes: dict[tuple[str, str], float] = {}
    if manifest_path and Path(manifest_path).exists():
        for r in load_manifest(manifest_path):
            key = (r["speaker"], r["accent"])
            minutes[key] = minutes.get(key, 0.0) + r["duration"] / 60

    vc_ok, vc_reason = (False, "no voice conversion model chosen")
    if vc_model:
        try:
            registry.require(vc_model, mode)
            vc_ok, vc_reason = True, "ok"
        except Exception as e:  # LicenceError or unknown model
            vc_ok, vc_reason = False, str(e)

    rows = []
    for accent, cells in voices["plan"].items():
        for voice_type, method in cells.items():
            need = methods[method]["min_minutes"]
            base_scope = "tts_training" if method == "tts_speaker" else "voice_conversion"
            scopes = needed_scopes(base_scope, mode)
            candidates = []
            for spk in ledger.speakers.values():
                if method == "tts_speaker" and spk.accent != accent:
                    continue
                if voice_type not in spk.voice_types:
                    continue
                ok, _ = spk.check(scopes)
                if ok:
                    candidates.append(spk.id)
            have = sum(minutes.get((s, accent), 0.0) for s in candidates) if method == "tts_speaker" else None
            if method == "vc_timbre" and not vc_ok:
                status, detail = "blocked", vc_reason
            elif not candidates:
                status, detail = "need_speaker", "no consenting speaker for this accent and voice type"
            elif method == "tts_speaker" and (have or 0) < need:
                status, detail = "need_data", f"{have:.1f} of {need} minutes recorded"
            else:
                status, detail = "ready", "ok"
            rows.append({"accent": accent, "voice_type": voice_type, "method": method,
                         "speakers": candidates, "minutes": None if have is None else round(have, 1),
                         "needed_minutes": need, "status": status, "detail": detail})
    return rows
